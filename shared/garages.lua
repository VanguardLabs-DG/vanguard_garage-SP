-- Adiciona as 75 garagens do Config.Garages
for gid, g in pairs(Config.Garages) do
    local markerCoord = vec3(g.marker_x, g.marker_y, g.marker_z)
    local spawns = {}
    if g.spawns and type(g.spawns) == "table" and #g.spawns > 0 then
        spawns = g.spawns
    else
        spawns = { vec4(g.spawn_x, g.spawn_y, g.spawn_z, g.spawn_h) }
    end

    local vType = {"car", "motorcycle", "cycles"}
    local lowerName = string.lower(g.name or "")
    if string.find(lowerName, "bike") then
        vType = {"cycles"}
    elseif string.find(lowerName, "aero") or string.find(lowerName, "hangar") or string.find(lowerName, "heli") then
        vType = {"planes", "helicopter"}
    elseif string.find(lowerName, "boat") or string.find(lowerName, "barco") then
        vType = {"boat"}
    end

    local perm = g.permission or ""
    if perm == "nil" or perm == "false" then perm = "" end

    local gidLower = string.lower(gid)
    local isSecretOrFaction = gidLower:find("mafa") or gidLower:find("drogas") or gidLower:find("bunker") or gidLower:find("contraban") or gidLower:find("heineken") or gidLower:find("desmanche") or gidLower:find("pessoal") or gidLower:find("77777") or gidLower:find("prisao") or gidLower:find("gfav") or gidLower:find("mc") or gidLower:find("vanila") or gidLower:find("cerveja") or gidLower:find("gcm") or gidLower:find("taxi") or gidLower:find("hospital")

    if gidLower:find("gcm") and perm == "" then perm = "GCM" end
    if gidLower:find("taxi") and perm == "" then perm = "Taxi" end
    if gidLower:find("hospital") and perm == "" then perm = "Paramedico" end

    -- Identifica se é garagem de trabalho / viaturas / serviço
    local workKey = nil
    if Config.Works then
        if Config.Works[g.name] then
            workKey = g.name
        elseif perm ~= "" and Config.Works[perm] then
            workKey = perm
        elseif Config.Works[gid] then
            workKey = gid
        else
            local pLower = string.lower(perm ~= "" and perm or g.name or "")
            if (pLower == "paramedic" or pLower == "paramedico" or pLower == "hp") and Config.Works["Paramedico"] then
                workKey = "Paramedico"
            elseif (pLower == "bombeiro" or pLower == "bm") and Config.Works["BM"] then
                workKey = "BM"
            elseif (pLower == "mechanic" or pLower == "mecanico" or pLower == "mec" or pLower == "mec1" or pLower == "mec2" or pLower == "mec3") and Config.Works["Mechanic"] then
                workKey = "Mechanic"
            elseif (pLower:find("pm") or pLower == "qcg") and Config.Works["PM"] then
                workKey = "PM"
            elseif pLower:find("pc") and Config.Works["PC"] then
                workKey = "PC"
            elseif pLower:find("prf") and Config.Works["PRF"] then
                workKey = "PRF"
            elseif pLower:find("pf") and Config.Works["PF"] then
                workKey = "PF"
            elseif pLower:find("gcm") and Config.Works["GCM"] then
                workKey = "GCM"
            end
        end
    end

    local isWork = (workKey ~= nil)

    -- BLIP: Conforme solicitado pelo usuário, SOMENTE garagens públicas civis devem ser exibidas no mapa!
    -- Garagens de emprego/trabalho (PM, PC, PRF, SAMU, etc.), facções, ilegais e privadas NÃO têm blip no mapa.
    local isPublic = (perm == "") and not isWork and not isSecretOrFaction
    local blipConf = nil
    if isPublic and not string.find(lowerName, "bike") and not string.find(lowerName, "aero") and not string.find(lowerName, "hangar") and not string.find(lowerName, "heli") and not string.find(lowerName, "boat") then
        blipConf = { type = 357, sprite = 357, color = 32, scale = 0.6, label = "Garagem" }
    end

    GarageZone[gid] = {
        garage_id = gid,
        name = g.name or "Garage",
        label = g.name or "Garage",
        marker = markerCoord,
        marker_x = g.marker_x,
        marker_y = g.marker_y,
        marker_z = g.marker_z,
        spawnPoint = spawns,
        spawnpoint = spawns,
        type = vType,
        job = perm ~= "" and perm or (workKey or nil),
        permission = perm ~= "" and perm or (workKey or nil),
        isWork = isWork,
        workName = workKey,
        payment = g.payment or false,
        blip = blipConf,
        interaction = "keypressed",
        impound = false
    }
end

